const TYPE_TO_SKILL = new Map(CASE_TYPES.flatMap(g => g.types.map(([label, key]) => [label, key])));

export function getSkill(caseType) {
  const t = String(caseType || '').trim();
  let key = TYPE_TO_SKILL.get(t);
  if (!key && t) {
    // مطابقة تقريبية لأي نوع مكتوب بشكل مختلف
    for (const [label, k] of TYPE_TO_SKILL) {
      if (t.includes(label) || label.includes(t)) { key = k; break; }
    }
  }
  return { key: key || 'general', ...SKILLS[key || 'general'] };
}

export function formatSkill(skill) {
  return `مهارة: ${skill.title}
- القوانين الحاكمة: ${skill.laws.join('، ')}
- عناصر يجب إثباتها: ${skill.elements}
- دفوع شكلية محتملة: ${skill.formal}
- دفوع موضوعية محتملة: ${skill.substantive}
- مواعيد حرجة: ${skill.deadlines}
- أدلة مطلوبة عادة: ${skill.evidence}`;
}
