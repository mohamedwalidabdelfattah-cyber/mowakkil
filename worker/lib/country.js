const SA_REPLACEMENTS = [
  [/مستشار قانوني مصري/g, 'مستشار قانوني سعودي'],
  [/كمحامٍ مصري/g, 'كمحامٍ سعودي'],
  [/محامٍ مصري/g, 'محامٍ سعودي'],
  [/قانون العمل المصري/g, 'نظام العمل السعودي'],
  [/القانون المصري/g, 'الأنظمة السعودية'],
  [/المعتمد في مصر/g, 'المعتمد في المملكة العربية السعودية'],
  [/قاعدة البيانات القانونية المصرية \(5,828 مادة\)/g, 'مصادر الأنظمة السعودية'],
];

const SA_GUIDE = `

**المكتب ده في المملكة العربية السعودية (مهم جداً — بيغلب أي تعليمات قبله):**
- جاوب وفق الأنظمة السعودية ولوائحها التنفيذية والمبادئ القضائية السعودية، **مش القانون المصري**.
- أهم الأنظمة: نظام المرافعات الشرعية، نظام الإجراءات الجزائية، نظام الأحوال الشخصية (1443هـ)، نظام المعاملات المدنية (1444هـ)، نظام الإثبات (1443هـ)، نظام العمل، نظام المحاكم التجارية، نظام التنفيذ، نظام الإفلاس، نظام الشركات، نظام ديوان المظالم ونظام المرافعات أمام ديوان المظالم.
- الجهات: المحاكم العامة والجزائية والأحوال الشخصية والتجارية والعمالية ومحاكم التنفيذ، ومحاكم الاستئناف والمحكمة العليا، وديوان المظالم (القضاء الإداري)، والنيابة العامة، ومنصة ناجز.
- النصوص القانونية المرفقة من قاعدة البيانات (لو موجودة) **مصرية** — متعتمدش عليها في الإجابة السعودية.
- لو مش متأكد من رقم مادة أو مدة أو مبلغ بالضبط، قول كده صراحة، وانصح بالرجوع لنص النظام في موقع هيئة الخبراء بمجلس الوزراء (laws.boe.gov.sa).
- اكتب بالعربية الفصحى المبسطة، والتواريخ بالهجري مع الميلادي لو لزم.`;

export function localizeLegalPrompt(text, country) {
  if (normalizeCountry(country) !== 'SA') return text;
  let t = String(text || '');
  for (const [re, to] of SA_REPLACEMENTS) t = t.replace(re, to);
  return t + SA_GUIDE;
}

// دولة المكتب من الإعدادات (المكاتب القديمة = مصر)
export async function officeCountry(env, officeId) {
  if (!officeId) return 'EG';
  try {
    const r = await env.DB.prepare('SELECT country FROM office_settings WHERE office_id = ?').bind(officeId).first();
    return normalizeCountry(r?.country);
  } catch { return 'EG'; }
}
