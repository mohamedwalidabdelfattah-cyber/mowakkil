export const COUNTRIES = {
  EG: {
    code: 'EG', name: 'مصر', currency: 'EGP', vat: 14, timezone: 'Africa/Cairo', dial: '20',
    lawyer: 'محامٍ مصري', legalSystem: 'القانون المصري', lawWord: 'القانون', courts: 'المحاكم المصرية',
  },
  SA: {
    code: 'SA', name: 'المملكة العربية السعودية', currency: 'SAR', vat: 15, timezone: 'Asia/Riyadh', dial: '966',
    lawyer: 'محامٍ ومستشار قانوني سعودي', legalSystem: 'الأنظمة السعودية', lawWord: 'النظام', courts: 'المحاكم السعودية وديوان المظالم',
  },
};

export function normalizeCountry(c) {
  const v = String(c || '').toUpperCase();
  return COUNTRIES[v] ? v : 'EG';
}

export function countryProfile(c) { return COUNTRIES[normalizeCountry(c)]; }

