const sleep = ms => new Promise(r => setTimeout(r, ms));
const $ = s => document.querySelector(s);

// يقفل لوحة الإضافة لو مفتوحة (نفس زرار الفتح بيقفلها)
async function closePanel(id) {
  const panel = document.getElementById(id);
  if (panel && !panel.hidden) document.querySelector(`[data-toggle-panel="${id}"]`)?.click();
  await sleep(150);
}
// يقفل أي نافذة مفتوحة من غير ما يحفظ
async function closeModals() {
  for (const b of document.querySelectorAll('.modal-backdrop .modal-close, .ag-form button')) {
    if (b.textContent.trim() === '✕' || b.classList.contains('modal-close')) b.click();
  }
  await sleep(200);
  document.querySelectorAll('.modal-backdrop').forEach(m => m.remove());
}
