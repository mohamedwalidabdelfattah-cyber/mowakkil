const SKIP = 'script,style,textarea,input,[contenteditable],[data-no-msa],.chat-messages,.chat-message,.fu-preview,#fu-text,.ai-result,.analysis-result,code,pre,datalist';
const ATTRS = ['placeholder', 'title', 'aria-label'];
let observer = null;
let active = false;

function fixText(node) {
  const p = node.parentElement;
  if (!p || p.closest(SKIP)) return;
  // اختيار من غير value: النص نفسه هو القيمة اللي بتتحفظ — منغيّروش
  if (p.tagName === 'OPTION' && !p.hasAttribute('value')) return;
  const v = node.nodeValue;
  const t = toMSA(v);
  if (t !== v) node.nodeValue = t;
}
function fixEl(el) {
  if (el.nodeType !== 1 || el.closest(SKIP)) return;
  for (const a of ATTRS) {
    const v = el.getAttribute?.(a);
    if (v) { const t = toMSA(v); if (t !== v) el.setAttribute(a, t); }
  }
}
function walk(root) {
  if (!root) return;
  if (root.nodeType === 3) return fixText(root);
  if (root.nodeType !== 1) return;
  if (root.closest?.(SKIP)) return;
  fixEl(root);
  const tw = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let n = tw.nextNode();
  while (n) {
    if (n.nodeType === 3) fixText(n);
    else fixEl(n);
    n = tw.nextNode();
  }
}

const nativeConfirm = window.confirm.bind(window);
const nativeAlert = window.alert.bind(window);
const nativePrompt = window.prompt.bind(window);

export function startMSA() {
  if (!isSaudi()) return stopMSA();
  if (active) return;
  active = true;
  window.confirm = (m) => nativeConfirm(toMSA(String(m ?? '')));
  window.alert = (m) => nativeAlert(toMSA(String(m ?? '')));
  window.prompt = (m, d) => nativePrompt(toMSA(String(m ?? '')), d);
  walk(document.body);
  observer = new MutationObserver((muts) => {
    for (const m of muts) {
      if (m.type === 'characterData') fixText(m.target);
      else if (m.type === 'attributes') fixEl(m.target);
      else m.addedNodes.forEach(walk);
    }
  });
  observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  document.documentElement.setAttribute('data-msa', '1');
}

export function stopMSA() {
  if (!active) return;
  active = false;
  observer?.disconnect(); observer = null;
  window.confirm = nativeConfirm; window.alert = nativeAlert; window.prompt = nativePrompt;
  document.documentElement.removeAttribute('data-msa');
}
