// تظبيط بعد التحويل: ترتيب "بعد" في آخر الجملة
const POST = [
  [/ما زال (لم [\p{L}ً-ْ]+)/gu, '$1 بعد'],
  [/لا توجد بعدُ ([\p{L}]+)/gu, 'لا توجد $1 بعد'],
];

const RULES = [];
for (const [eg, msa, passive] of PHRASES) {
  const isWordy = /^[\p{L} ]+$/u.test(eg);
  if (passive === true) {
    // فعل مبني للمجهول + (اسم بعده؟) — eg هنا regex مقصود (فيه ? و |)
    // الاسم بعده = كلمة بتبدأ بـ "ال" (اتحفظت القضية → تم حفظ القضية)، غير كده: "تم الحفظ"
    RULES.push([new RegExp(B + '(?:' + eg + ')' + E + '(\\s+ال)?', 'gu'), (m, next) => (next ? msa + next : (PASSIVE_ALONE[msa] || msa))]);
    continue;
  }
  const src = eg.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  if (isWordy) {
    RULES.push([new RegExp(B + '(و|ف)?' + src + E, 'gu'), (m, pre) => (pre || '') + msa]);
  } else {
    RULES.push([new RegExp(src, 'gu'), msa]);
  }
}
RULES.push(...NEGATION);
for (const [eg, msa] of WORDS) RULES.push([W(eg), (m, pre) => (pre || '') + msa]);
RULES.push(...POST);

// كشف سريع: النص فيه أي كلمة من القاموس؟ (عشان منمررش كل النصوص على كل القواعد)
const TRIGGER = new RegExp([...PHRASES.map(p => p[0].split(/[ |?]/)[0]), ...WORDS.map(w => w[0])]
  .filter(Boolean).map(s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'u');

const cache = new Map();
export function toMSA(text) {
  if (!text || !/[؀-ۿ]/.test(text) || !TRIGGER.test(text)) return text;
  const hit = cache.get(text);
  if (hit !== undefined) return hit;
  let t = text;
  for (const [re, to] of RULES) { re.lastIndex = 0; t = t.replace(re, to); }
  if (cache.size > 4000) cache.clear();
  cache.set(text, t);
  return t;
}

